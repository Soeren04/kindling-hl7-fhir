import { describe, expect, it } from "vitest";

import {
  isCode,
  isDate,
  isDateTime,
  isNumber,
  isSequenceId,
  isTime,
} from "../../../src/hl7v2/validate/formats";

/** Expects `check` to accept every value of `valid` and to reject every value of `invalid`. */
function table(
  check: (text: string) => boolean,
  valid: readonly string[],
  invalid: readonly string[],
): void {
  it.each(valid)("accepts %j", (text) => {
    expect(check(text)).toBe(true);
  });
  it.each(invalid)("rejects %j", (text) => {
    expect(check(text)).toBe(false);
  });
}

describe("isNumber (NM)", () => {
  table(
    isNumber,
    ["0", "196", "-1", "+1", "14.2", "007", ".5", "5.", "+.5", "-5.", "-0.25"],
    [
      "",
      "+",
      "-",
      ".",
      "+.",
      "1.2.3",
      "1,5",
      "1e3",
      " 1",
      "1 ",
      "--1",
      "1-",
      "NaN",
      "١",
    ],
  );
});

describe("isSequenceId (SI)", () => {
  table(
    isSequenceId,
    ["0", "1", "0001", "9999"],
    ["", "-1", "+1", "1.0", "a", " 1"],
  );
});

