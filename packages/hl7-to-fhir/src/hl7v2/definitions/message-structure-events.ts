// The message structure of each message code and trigger event (MSH-9.1 and MSH-9.2), as of HL7 v2.5.1.
//
// Source of record: HL7 Terminology (THO, CC0), https://github.com/HL7/UTG at commit
// 05d22fc29bccb5ca5e60e249ec153da4ad07af58, input/sourceOfTruth/v2/codeSystems/cs-v2-0354.xml (version 3.0.0): the
// events listed with each structure code. The message code is the part of the structure code before the underscore.
//
// THO lists the events of the current version of HL7 v2, not of 2.5.1, and it assigns a few events to a second
// structure code. The map is therefore derived for 2.5.1 as follows, and checked against the event map and the
// message classes of HAPI hapi-structures-v251 2.5.1:
// - An event belongs to the structure of the same name (ADT^A04 would be ADT_A04) unless 2.5.1 reuses the structure
//   of another event: ADT^A04 is ADT_A01, ORU^R31 and ORU^R32 are ORU_R30, ADT^A44 is ADT_A43, ADT^A55 is ADT_A52,
//   RSP^K22 is RSP_K21, PIN^I07 is RQI_I01, QRY^T12 is QRY, and MFN^M14 is MFN_Znn.
// - An event whose structure 2.5.1 does not define is left out, so the later structures THO lists (for example
//   ORU_W01 or ORL_O40) have no entry.
// - Pairs whose message code or event is not in tables 0076 and 0003 are left out (the Z events, ADT^AXX, MFN^Znn,
//   QBP^Qnn and RTB^Knn).
// Callers fall back to MSH-9.3, or report the structure as unknown.

